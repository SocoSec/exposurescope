// Fill "{name}" placeholders: fill("Resend in {s}s", { s: 30 }) → "Resend in 30s".
export function fill(text, vars = {}) {
  return String(text).replace(/\{(\w+)\}/g, (_, key) => (key in vars ? String(vars[key]) : ""));
}

// Turn an API error body ({ error, retryAfter }) into a sentence in language L.
export function errorText(L, data) {
  const code = data && data.error;
  const template = (code && L.errors[code]) || L.errors.generic;
  const minutes = Math.max(1, Math.ceil(((data && data.retryAfter) || 60) / 60));
  return fill(template, { min: minutes });
}
